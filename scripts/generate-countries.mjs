#!/usr/bin/env node
// ============================================================================
// Generates lib/countries.ts: every country on the forms, with its English and
// its Arabic name. Names come from the Intl data that ships with Node, so they
// match what people expect to read in each language.
//
// Run it with: npm run gen:countries
// ============================================================================

import { writeFileSync } from "node:fs";
import { join } from "node:path";

// ISO 3166-1 alpha-2, officially assigned, minus the uninhabited territories
// that have no place on a business form (Antarctica, Bouvet Island and so on).
const CODES = [
  "AD", "AE", "AF", "AG", "AI", "AL", "AM", "AO", "AR", "AS", "AT", "AU",
  "AW", "AX", "AZ", "BA", "BB", "BD", "BE", "BF", "BG", "BH", "BI", "BJ",
  "BL", "BM", "BN", "BO", "BQ", "BR", "BS", "BT", "BW", "BY", "BZ", "CA",
  "CC", "CD", "CF", "CG", "CH", "CI", "CK", "CL", "CM", "CN", "CO", "CR",
  "CU", "CV", "CW", "CX", "CY", "CZ", "DE", "DJ", "DK", "DM", "DO", "DZ",
  "EC", "EE", "EG", "EH", "ER", "ES", "ET", "FI", "FJ", "FK", "FM", "FO",
  "FR", "GA", "GB", "GD", "GE", "GF", "GG", "GH", "GI", "GL", "GM", "GN",
  "GP", "GQ", "GR", "GT", "GU", "GW", "GY", "HK", "HN", "HR", "HT", "HU",
  "ID", "IE", "IL", "IM", "IN", "IO", "IQ", "IR", "IS", "IT", "JE", "JM",
  "JO", "JP", "KE", "KG", "KH", "KI", "KM", "KN", "KP", "KR", "KW", "KY",
  "KZ", "LA", "LB", "LC", "LI", "LK", "LR", "LS", "LT", "LU", "LV", "LY",
  "MA", "MC", "MD", "ME", "MF", "MG", "MH", "MK", "ML", "MM", "MN", "MO",
  "MP", "MQ", "MR", "MS", "MT", "MU", "MV", "MW", "MX", "MY", "MZ", "NA",
  "NC", "NE", "NF", "NG", "NI", "NL", "NO", "NP", "NR", "NU", "NZ", "OM",
  "PA", "PE", "PF", "PG", "PH", "PK", "PL", "PM", "PN", "PR", "PS", "PT",
  "PW", "PY", "QA", "RE", "RO", "RS", "RU", "RW", "SA", "SB", "SC", "SD",
  "SE", "SG", "SH", "SI", "SJ", "SK", "SL", "SM", "SN", "SO", "SR", "SS",
  "ST", "SV", "SX", "SY", "SZ", "TC", "TD", "TG", "TH", "TJ", "TK", "TL",
  "TM", "TN", "TO", "TR", "TT", "TV", "TW", "TZ", "UA", "UG", "US", "UY",
  "UZ", "VA", "VC", "VE", "VG", "VI", "VN", "VU", "WF", "WS", "YE", "YT",
  "ZA", "ZM", "ZW",
];

// Where the firm glossary uses a different wording from the Intl data, the
// glossary wins, so the forms match the rest of the Arabic copy.
const AR_OVERRIDES = {
  OM: "سلطنة عُمان",
  VG: "جزر العذراء البريطانية",
  CG: "جمهورية الكونغو",
  CD: "جمهورية الكونغو الديمقراطية",
  TL: "تيمور ليشتي",
};

// The Intl data writes the two Congos with a spaced hyphen, which the house
// style does not allow. These are the forms the site uses instead.
const EN_OVERRIDES = {
  CG: "Republic of the Congo",
  CD: "Democratic Republic of the Congo",
};

const english = new Intl.DisplayNames(["en"], { type: "region" });
const arabic = new Intl.DisplayNames(["ar"], { type: "region" });

const rows = CODES.map((code) => {
  const en = EN_OVERRIDES[code] ?? english.of(code);
  const ar = AR_OVERRIDES[code] ?? arabic.of(code);
  if (!en || en === code) throw new Error(`No English name for ${code}`);
  if (!ar || ar === code) throw new Error(`No Arabic name for ${code}`);
  // The house style bans dashes in visible copy, so catch any that the Intl
  // data introduces before they reach the forms.
  for (const name of [en, ar]) {
    if (/—|–|\S \- \S/.test(name)) {
      throw new Error(`Dash in the name for ${code}: ${name}`);
    }
  }
  return { code, en, ar };
});

// Sorted by the English name, which is the order the English forms show.
rows.sort((a, b) => a.en.localeCompare(b.en, "en"));

const body = rows
  .map((r) => `  { code: "${r.code}", en: "${r.en}", ar: "${r.ar}" },`)
  .join("\n");

const file = `// ============================================================================
// Generated by scripts/generate-countries.mjs. Do not edit by hand.
// Run "npm run gen:countries" to rebuild it.
//
// Every country offered in the site forms, with its English and Arabic name.
// ============================================================================

export interface Country {
  /** ISO 3166-1 alpha-2 code. */
  code: string;
  en: string;
  ar: string;
}

export const COUNTRIES: Country[] = [
${body}
];

/** Looks a country up by its code. */
export function countryByCode(code: string): Country | undefined {
  return COUNTRIES.find((country) => country.code === code);
}
`;

const out = join(process.cwd(), "lib", "countries.ts");
writeFileSync(out, file, "utf8");
console.log(`Wrote ${rows.length} countries to lib/countries.ts`);
